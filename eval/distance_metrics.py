"""Which distance metric should retrieval use? A small, reproducible comparison.

Retrieval ranks passages by how close their vectors are to the question's vector.
"Close" can be measured in several ways:

    cosine similarity   angle between the vectors (ignores their length)
    dot product         sum of element-wise products (affected by length)
    Euclidean (L2)      straight-line distance
    Manhattan (L1)      sum of absolute differences

Key fact: for vectors normalized to length 1, Euclidean distance and cosine
similarity give exactly the same ranking, because
    ||a - b||^2 = ||a||^2 + ||b||^2 - 2 a.b = 2 - 2 cos(a, b).
That is why GreenScope normalizes every vector and uses FAISS IndexFlatIP
(inner product): on unit vectors, inner product = cosine.

This script measures every metric on raw (unnormalized) and normalized
the app's embedding vectors over the 40-question eval set. Retrieval only, no API cost.

Run:  python eval/distance_metrics.py   ->   eval/distance_metrics.md
"""

import json
import sys
from pathlib import Path
from statistics import mean

import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from src.data import (  # noqa: E402
    CHUNK_OVERLAP, CHUNK_SIZE, COMPANIES, EMBEDDING_MODEL_NAME, QUERY_PREFIX, RAW_DATA_DIR,
    chunk_pages, get_embedding_model, load_pdf,
)
from src.model import prepare_query  # noqa: E402

EVAL_DIR = PROJECT_ROOT / "eval"
TOP_K = 5


def scores_by_metric(q, C):
    """Higher score = closer, for every metric (distances are negated)."""
    q_unit = q / np.linalg.norm(q)
    C_unit = C / np.linalg.norm(C, axis=1, keepdims=True)
    return {
        "Cosine similarity": C_unit @ q_unit,
        "Dot product (raw vectors)": C @ q,
        "Euclidean (raw vectors)": -np.linalg.norm(C - q, axis=1),
        "Euclidean (normalized vectors)": -np.linalg.norm(C_unit - q_unit, axis=1),
        "Manhattan (raw vectors)": -np.abs(C - q).sum(axis=1),
        "Manhattan (normalized vectors)": -np.abs(C_unit - q_unit).sum(axis=1),
    }


def main():
    eval_set = json.loads((EVAL_DIR / "eval_set.json").read_text())
    model = get_embedding_model()
    ranks = {}         # metric -> list of first-hit ranks
    same_top5 = {}     # metric -> share of questions whose top-5 pages equal cosine's
    norms = []
    for company, filename in COMPANIES.items():
        chunks = chunk_pages(load_pdf(RAW_DATA_DIR / filename, company))
        pages = [c.metadata["page"] for c in chunks]
        C = model.encode([c.page_content for c in chunks], batch_size=64, normalize_embeddings=False)
        norms.extend(np.linalg.norm(C, axis=1).tolist())
        for item in [q for q in eval_set if q["company"] == company]:
            q = model.encode(QUERY_PREFIX + prepare_query(item["question"]), normalize_embeddings=False)
            all_scores = scores_by_metric(q, C)
            cosine_top = list(np.argsort(-all_scores["Cosine similarity"])[:TOP_K])
            for metric, s in all_scores.items():
                top = list(np.argsort(-s)[:TOP_K])
                gold = set(item["gold_pages"])
                rank = next((r for r, i in enumerate(top, start=1) if pages[i] in gold), None)
                ranks.setdefault(metric, []).append(rank)
                same_top5.setdefault(metric, []).append(top == cosine_top)

    already_unit = max(norms) - min(norms) < 1e-3
    lines = [
        "# Distance metrics for retrieval",
        "",
        f"Generated by `python eval/distance_metrics.py` ({EMBEDDING_MODEL_NAME}, {CHUNK_SIZE}/{CHUNK_OVERLAP} chunks, 40 questions, "
        "retrieval only).",
        "",
        (f"The model already outputs vectors of length 1 (norm min {min(norms):.3f}, max {max(norms):.3f}), "
         "so 'raw' and 'normalized' vectors are the same here."
         if already_unit else
         f"Raw chunk vectors are not all the same length (norm min {min(norms):.2f}, "
         f"max {max(norms):.2f}), so metrics that use the length can rank passages differently."),
        "",
        "| Metric | MRR@5 | Hit@1 | Hit@5 | Top 5 identical to cosine |",
        "|---|---|---|---|---|",
    ]
    for metric, r in ranks.items():
        lines.append(
            f"| {metric} | {mean(1 / x if x else 0 for x in r):.3f} | {mean(1.0 if x == 1 else 0.0 for x in r):.2f} | "
            f"{mean(1.0 if x else 0.0 for x in r):.2f} | {mean(same_top5[metric]) * 100:.0f}% of questions |"
        )
    lines += [
        "",
        "## Reading the table",
        "",
        "- **Cosine, dot product and Euclidean distance rank identically on unit vectors** (top 5 identical for every "
        "question), as the formula ||a-b||² = 2 - 2·cos(a,b) predicts. Choosing between them is a matter "
        "of convenience, not accuracy.",
        ("- **Dot product** equals cosine similarity here because every vector has length 1. With "
         "vectors of different lengths it would also reward length, which reflects text properties "
         "rather than relevance."
         if already_unit else
         "- **Dot product on raw vectors** also rewards vector length, which reflects text properties "
         "rather than relevance, so it can promote passages for the wrong reason."),
        "- **Manhattan (L1)** is a different geometry; it is rarely used for sentence embeddings because "
        "the models are trained with cosine similarity.",
        "- GreenScope normalizes all vectors and searches by inner product (FAISS `IndexFlatIP`), which "
        "equals cosine similarity and matches how the embedding model was trained.",
        "",
    ]
    (EVAL_DIR / "distance_metrics.md").write_text("\n".join(lines))
    print("\n".join(lines[6:6 + 2 + len(ranks)]))


if __name__ == "__main__":
    main()
