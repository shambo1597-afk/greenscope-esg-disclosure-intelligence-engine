"""Retrieval evaluation for GreenScope (no API calls, so it costs nothing).

For each question in eval/eval_set.json we search that company's report and
check whether the retrieved chunks come from a "gold" page, i.e. a page where
the answer actually appears in the PDF.

Metrics (all between 0 and 1, higher is better):
    Hit@k         Did at least one of the top k chunks come from a gold page?
    MRR@5         Mean Reciprocal Rank: 1 if the first chunk is relevant,
                  1/2 if the first relevant one is 2nd, ... 0 if none in top 5.
    Precision@5   What fraction of the top 5 chunks are from gold pages?

Run from the project root:  python eval/run_eval.py
Results are printed and written to eval/results.md. The app's default
(company names removed from the query) is compared with searching the
question exactly as typed.
"""

import json
import sys
from pathlib import Path
from statistics import mean

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))  # so "from src..." works when run as a script

from src.data import CHUNK_OVERLAP, CHUNK_SIZE, EMBEDDING_MODEL_NAME  # noqa: E402
from src.model import ReportIndex  # noqa: E402

EVAL_DIR = PROJECT_ROOT / "eval"
K_VALUES = (1, 3, 5)
MAX_K = max(K_VALUES)


def score_question(retrieved_pages, gold_pages):
    """Compute all metrics for one question from the ranked list of pages."""
    gold = set(gold_pages)
    relevant = [page in gold for page in retrieved_pages]
    first_hit = next((rank for rank, ok in enumerate(relevant, start=1) if ok), None)
    scores = {f"Hit@{k}": float(any(relevant[:k])) for k in K_VALUES}
    scores["MRR@5"] = 1.0 / first_hit if first_hit else 0.0
    scores["Precision@5"] = sum(relevant[:MAX_K]) / MAX_K
    return scores, first_hit


def summarise(rows):
    metric_names = [f"Hit@{k}" for k in K_VALUES] + ["MRR@5", "Precision@5"]
    return {m: mean(r["scores"][m] for r in rows) for m in metric_names}


def evaluate(index, eval_set, neutralize_names):
    """Run every question through retrieval and score it."""
    rows = []
    for item in eval_set:
        chunks = index.retrieve(item["question"], item["company"], top_k=MAX_K,
                                neutralize_names=neutralize_names)
        pages = [c.page for c in chunks]
        scores, first_hit = score_question(pages, item["gold_pages"])
        rows.append({**item, "retrieved_pages": pages, "first_hit": first_hit, "scores": scores})
    return rows


def group_rows(rows):
    """Split results per company, plus an 'Overall' group."""
    groups = {c: [r for r in rows if r["company"] == c] for c in sorted({r["company"] for r in rows})}
    groups["Overall"] = rows
    return groups


def main():
    eval_set = json.loads((EVAL_DIR / "eval_set.json").read_text())
    index = ReportIndex()

    rows = evaluate(index, eval_set, neutralize_names=True)
    groups = group_rows(rows)
    summary = {name: summarise(group) for name, group in groups.items()}
    metric_names = list(summary["Overall"])

    # Ablation: the same questions searched exactly as typed (company names kept).
    raw_summary = {name: summarise(g) for name, g in group_rows(evaluate(index, eval_set, False)).items()}

    # --- Console output -------------------------------------------------------
    print(f"{'':10}" + "".join(f"{m:>13}" for m in metric_names))
    for name, s in summary.items():
        print(f"{name:10}" + "".join(f"{s[m]:>13.2f}" for m in metric_names))
    print(f"(company names kept in query: overall Hit@5 {raw_summary['Overall']['Hit@5']:.2f})")

    # --- Markdown report --------------------------------------------------------
    lines = [
        "# GreenScope retrieval evaluation",
        "",
        "Generated by `python eval/run_eval.py`. Retrieval only: no LLM calls.",
        "",
        f"Settings: `{EMBEDDING_MODEL_NAME}`, chunk_size={CHUNK_SIZE}, chunk_overlap={CHUNK_OVERLAP}, "
        f"FAISS IndexFlatIP (cosine), top {MAX_K} chunks per question, {len(rows)} questions.",
        "",
        "## Summary",
        "",
        "| Group | n | " + " | ".join(metric_names) + " |",
        "|---|---|" + "---|" * len(metric_names),
    ]
    for name, s in summary.items():
        lines.append(f"| {name} | {len(groups[name])} | " + " | ".join(f"{s[m]:.2f}" for m in metric_names) + " |")

    lines += [
        "",
        "## Effect of removing company names from the search query",
        "",
        "The app replaces \"Wipro\" / \"HCLTech\" in the question with \"the company\" before searching "
        "(`prepare_query` in `src/model.py`), because each search already runs inside one company's "
        "report. The table below is the same evaluation with the question searched exactly as typed.",
        "",
        "| Group | Hit@5 as typed | Hit@5 names removed (used by the app) | MRR@5 as typed | MRR@5 names removed |",
        "|---|---|---|---|---|",
    ]
    for name in summary:
        lines.append(f"| {name} | {raw_summary[name]['Hit@5']:.2f} | {summary[name]['Hit@5']:.2f} | "
                     f"{raw_summary[name]['MRR@5']:.2f} | {summary[name]['MRR@5']:.2f} |")

    lines += [
        "",
        "## Per question",
        "",
        "Retrieved pages are listed in rank order; **bold** = a gold page.",
        "",
        "| ID | Question | Gold pages | Retrieved pages (top 5) | First hit rank |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        gold = set(r["gold_pages"])
        retrieved = ", ".join(f"**{p}**" if p in gold else str(p) for p in r["retrieved_pages"])
        hit = r["first_hit"] if r["first_hit"] else "miss"
        lines.append(f"| {r['id']} | {r['question']} | {', '.join(map(str, r['gold_pages']))} | {retrieved} | {hit} |")

    lines += [
        "",
        "## Metric definitions",
        "",
        "- **Hit@k**: share of questions where at least one of the top k chunks comes from a gold page.",
        "- **MRR@5**: average of 1/rank of the first gold-page chunk (0 if none in the top 5).",
        "- **Precision@5**: average share of the top 5 chunks that come from gold pages.",
        "",
        "## Limitations",
        "",
        "- **Small eval set.** 40 questions (20 per company) is enough to spot gross failures, "
        "not to measure small differences. One question changes a per-company score by 0.05.",
        "- **Page-level matching only.** A chunk counts as relevant if it is on a gold page, even if "
        "it is a different paragraph of that page. A chunk on a non-gold page that does contain the "
        "answer counts as a miss if we did not list that page.",
        "- **Gold pages were found by keyword search** of the extracted PDF text and have not yet been "
        "checked by a person (`\"verified\": false` in `eval_set.json`). Some pages that mention the "
        "answer in other words may be missing from the gold lists.",
        "- **Retrieval only.** These numbers say whether the right evidence reaches the LLM; they do not "
        "measure whether the generated answer is correct or correctly cited.",
        "- **Precision@5 has a ceiling.** When only one or two pages hold the answer, even perfect "
        "retrieval cannot fill all 5 slots with gold pages, so low Precision@5 is expected.",
        "",
    ]
    (EVAL_DIR / "results.md").write_text("\n".join(lines))
    print(f"\nWrote {EVAL_DIR / 'results.md'}")


if __name__ == "__main__":
    main()
