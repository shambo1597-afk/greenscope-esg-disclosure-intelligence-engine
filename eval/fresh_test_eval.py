"""Run the frozen fresh test set once: retrieval metrics + graded answers.

eval/fresh_test_set.json was written and committed BEFORE this script was run,
and no setting was changed afterwards, so these are true held-out numbers. It
includes table, infographic and unanswerable questions.

Same pipeline as the app (split_question, retrieve_multi, answer_request) and
the same judge as eval/answer_eval.py, 3 runs per question. Writes
eval/fresh_test_results.md and .json. Costs about US$0.75.

    python eval/fresh_test_eval.py
"""

import json
import sys
from collections import Counter
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))
sys.path.insert(0, str(PROJECT_ROOT / "eval"))

import anthropic  # noqa: E402

from answer_eval import JUDGE_MODEL, JUDGE_SCHEMA, JUDGE_SYSTEM  # noqa: E402
from run_eval import evaluate, summarise  # noqa: E402
from src.model import (DEFAULT_TOP_K, ReportIndex, answer_request, format_context,  # noqa: E402
                       get_api_key, split_question)

EVAL_DIR = PROJECT_ROOT / "eval"
RUNS = 3
HAIKU = (1.00, 5.00)   # US$ per million input / output tokens (standard API)
JUDGE = (2.00, 10.00)
LETTER = {"correct": "C", "partly_correct": "P", "contains_error": "E", "missed": "M"}


def cost(usage, prices):
    return (usage.input_tokens * prices[0] + usage.output_tokens * prices[1]) / 1e6


def main():
    client = anthropic.Anthropic(api_key=get_api_key())
    questions = json.loads((EVAL_DIR / "fresh_test_set.json").read_text(encoding="utf-8"))
    index = ReportIndex()

    answerable = [q for q in questions if q["gold_pages"]]
    retrieval = {r["id"]: r for r in evaluate(index, answerable, neutralize_names=True)}

    rows, spent = [], 0.0
    for q in questions:
        split = split_question(q["question"])
        spent += split.cost_usd
        chunks = index.retrieve_multi(q["question"], q["company"], DEFAULT_TOP_K, split.queries)
        context = format_context(chunks)
        for run in range(1, RUNS + 1):
            response = client.messages.create(**answer_request(q["question"], chunks))
            answer = "".join(b.text for b in response.content if b.type == "text")
            judged = client.messages.create(
                model=JUDGE_MODEL, max_tokens=4000, system=JUDGE_SYSTEM,
                output_config={"effort": "low", "format": {"type": "json_schema", "schema": JUDGE_SCHEMA}},
                messages=[{"role": "user", "content": (
                    f"Question: {q['question']}\n\nReference answer: {q['expected_answer']}\n\n"
                    f"Report excerpts given to the assistant:\n\n{context}\n\nAssistant's answer:\n{answer}")}],
            )
            verdict = json.loads("".join(b.text for b in judged.content if b.type == "text"))
            spent += cost(response.usage, HAIKU) + cost(judged.usage, JUDGE)
            rows.append({"id": q["id"], "run": run, "type": q["type"], "company": q["company"],
                         "question": q["question"], "answer": answer, **verdict})
            print(f"{q['id']} run {run}: {verdict['verdict']}")

    (EVAL_DIR / "fresh_test_results.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    write_report(questions, rows, retrieval, spent)


def write_report(questions, rows, retrieval, spent):
    by_q = {}
    for r in rows:
        by_q.setdefault(r["id"], []).append(r)
    counts = Counter(r["verdict"] for r in rows)
    n = len(rows)
    all_correct = sum(all(r["verdict"] == "correct" for r in v) for v in by_q.values())
    cited = [r for r in rows if r["citations_supported"] is not None]
    ret = summarise(list(retrieval.values()))
    lines = [
        "# Fresh test set: held-out results",
        "",
        "Generated by `python eval/fresh_test_eval.py`. The 20 questions in `eval/fresh_test_set.json` "
        "were written and committed before this run, and no setting was changed afterwards, so this is "
        "a true held-out test. They were written by the same assistant that built the system (not by "
        "an outside person), and gold pages were found by searching the extracted text; they are not "
        f"human-verified. Same pipeline and judge ({JUDGE_MODEL}) as `eval/answer_eval.py`, "
        f"{RUNS} runs per question. Total cost: US${spent:.2f}.",
        "",
        "## Answers",
        "",
        "| | Answers | Correct | Partly correct | Contains an error | Missed |",
        "|---|---|---|---|---|---|",
        f"| All 20 questions | {n} | {counts['correct']} ({counts['correct'] / n:.0%}) | "
        f"{counts['partly_correct']} | {counts['contains_error']} | {counts['missed']} |",
    ]
    for kind in ["text", "table", "infographic", "unanswerable"]:
        sub = [r for r in rows if r["type"] == kind]
        if sub:
            c = Counter(r["verdict"] for r in sub)
            lines.append(f"| {kind} ({len(sub) // RUNS} questions) | {len(sub)} | {c['correct']} | "
                         f"{c['partly_correct']} | {c['contains_error']} | {c['missed']} |")
    lines += [
        "",
        f"- **Questions correct in all {RUNS} runs:** {all_correct} of {len(by_q)}.",
        f"- **Citations supported** (every citation backs its claim): "
        f"{sum(bool(r['citations_supported']) for r in cited)} of {len(cited)} answers.",
        "",
        f"## Retrieval (the {len(retrieval)} answerable questions)",
        "",
        "| Hit@1 | Hit@3 | Hit@5 | MRR@5 | Precision@5 |",
        "|---|---|---|---|---|",
        f"| {ret['Hit@1']:.2f} | {ret['Hit@3']:.2f} | {ret['Hit@5']:.2f} | {ret['MRR@5']:.2f} | {ret['Precision@5']:.2f} |",
        "",
        "## Per question",
        "",
        "| ID | Type | Question | Runs | Retrieved pages | Judge's note on the first non-correct run |",
        "|---|---|---|---|---|---|",
    ]
    for q in questions:
        v = by_q[q["id"]]
        bad = next((r for r in v if r["verdict"] != "correct"), None)
        note = bad["explanation"].replace("|", "/").replace("\n", " ") if bad else ""
        pages = retrieval[q["id"]]["retrieved_pages"] if q["id"] in retrieval else "n/a"
        lines.append(f"| {q['id']} | {q['type']} | {q['question']} | "
                     f"{' '.join(LETTER.get(r['verdict'], '?') for r in v)} | {pages} | {note} |")
    text = "\n".join(lines) + "\n"
    (EVAL_DIR / "fresh_test_results.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
