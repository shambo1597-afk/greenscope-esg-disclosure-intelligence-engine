"""Does splitting two-topic questions help? (eval/multi_topic_set.json, 8 questions)

For each question, a topic counts as COVERED if any retrieved passage comes from one
of that topic's gold pages. We compare:
    single, top 5    the question searched as typed (what the app did before)
    single, top 10   the same with as many passages as split search can return,
                     to separate "splitting helps" from "more passages help"
    split, top 5 each  split_question() + retrieve_multi() (what the app does now)

Splitting calls Claude Haiku once per question (about US$0.0002 each).
Run:  python eval/multi_topic_eval.py   ->   eval/multi_topic_results.md
"""

import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from src.model import ReportIndex, has_api_key, split_question  # noqa: E402

EVAL_DIR = PROJECT_ROOT / "eval"


def covered(results, topics):
    pages = {r.page for r in results}
    return [bool(pages & set(t["gold_pages"])) for t in topics]


def main():
    if not has_api_key():
        sys.exit("Needs an Anthropic API key (splitting uses Claude Haiku).")
    items = json.loads((EVAL_DIR / "multi_topic_set.json").read_text())
    index = ReportIndex()
    methods = ["single, top 5", "single, top 10", "split, top 5 each"]
    rows, cost = [], 0.0
    for item in items:
        split = split_question(item["question"])
        cost += split.cost_usd
        found = {
            "single, top 5": index.retrieve(item["question"], item["company"], 5),
            "single, top 10": index.retrieve(item["question"], item["company"], 10),
            "split, top 5 each": index.retrieve_multi(item["question"], item["company"], 5, split.queries),
        }
        rows.append((item, split.queries, {m: covered(found[m], item["topics"]) for m in methods},
                     {m: len(found[m]) for m in methods}))

    lines = [
        "# Two-topic questions: single search vs split search",
        "",
        "Generated by `python eval/multi_topic_eval.py` (8 questions, 2 topics each; "
        f"splitting cost US${cost:.4f}). A topic is covered if a passage from one of its gold pages "
        "is retrieved.",
        "",
        "| Method | Both topics covered | Topics covered | Passages sent |",
        "|---|---|---|---|",
    ]
    for m in methods:
        both = sum(all(r[2][m]) for r in rows)
        topics = sum(sum(r[2][m]) for r in rows)
        passages = sum(r[3][m] for r in rows) / len(rows)
        lines.append(f"| {m} | {both} of {len(rows)} | {topics} of {2 * len(rows)} | {passages:.1f} on average |")
    lines += ["", "## Per question", "", "| ID | Question | Split into | single 5 | single 10 | split |", "|---|---|---|---|---|---|"]
    for item, queries, cov, _ in rows:
        cell = {m: " / ".join("✓" if c else "✗" for c in cov[m]) for m in methods}
        lines.append(f"| {item['id']} | {item['question']} | {' · '.join(queries)} | {cell[methods[0]]} | "
                     f"{cell[methods[1]]} | {cell[methods[2]]} |")
    lines += ["", "✓ / ✗ = first topic / second topic covered.", "",
              "Limitations: 8 questions; gold pages found by keyword search (not yet human-verified).", ""]
    (EVAL_DIR / "multi_topic_results.md").write_text("\n".join(lines))
    print("\n".join(lines[5:9]))


if __name__ == "__main__":
    main()
