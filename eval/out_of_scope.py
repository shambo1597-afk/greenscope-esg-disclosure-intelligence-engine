"""Check that GreenScope declines questions the reports don't answer.

Runs the app's exact pipeline (retrieve, explain, generate) on questions whose
answers are not in the reports and saves the answers to eval/out_of_scope.md.
Costs well under one US cent.

    python eval/out_of_scope.py
"""

import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from src.model import DEFAULT_TOP_K, ReportIndex, generate_answer  # noqa: E402

QUESTIONS = [
    ("Wipro", "What was Wipro's total water consumption in 2010?"),
    ("Wipro", "How much cryptocurrency does Wipro hold on its balance sheet?"),
    ("HCLTech", "How many electric vehicle charging points does HCLTech operate in Brazil?"),
    ("HCLTech", "What is HCLTech's share price target for 2026?"),
]


def main():
    index = ReportIndex()
    lines = [
        "# Out-of-scope questions: does GreenScope decline?",
        "",
        "Generated by `python eval/out_of_scope.py` with the app's exact pipeline. The answers to "
        "these questions are not in the reports, so the correct behaviour is to say so "
        "(prompt rule 4) rather than answer from outside knowledge.",
        "",
    ]
    total = 0.0
    for company, question in QUESTIONS:
        chunks = index.retrieve(question, company, DEFAULT_TOP_K)
        answer = generate_answer(question, chunks)
        total += answer.cost_usd
        print(f"\n### {company}: {question}\n{answer.text or answer.error}")
        lines += [f"## {company}: {question}", "", (answer.text or answer.error).strip(), ""]
    lines.append(f"Total cost: US${total:.4f}.")
    (PROJECT_ROOT / "eval" / "out_of_scope.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
